const (
	defSDAPinName = "GPIO23"
	defSCLPinName = "GPIO24"
	defCSPinName  = "GPIO25"
	defRSTPinName = "GPIO26"
	defFBDevName  = "/dev/fb0"

	xOffset   = 60
	yOffset   = 0
	longSide  = 960
	shortSide = 480
)

