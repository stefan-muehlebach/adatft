// Dies ist der Datentyp, welche für die Verbindung zum ILI9341 via SPI
// steht. Im Wesentlichen handelt es sich dabei um den Filedescriptor auf
// das Device-File für die SPI-Verbindung und den Pin, welcher für die
// Command/Data-Leitung verwendet wird.
type GC9503CV struct {
	SDA, SCL, CS, RST gpio.PinIO
	fb                *framebuffer.Device
}

func Open(speedHz physic.Frequency) *GC9503CV {
	return Open2("", "", "", "", "")
}

func Open2(sda, scl, cs, rst string, fbdev string) *GC9503CV {
	var err error

	d := &GC9503CV{}
	if sda == "" {
		sda = defSDAPinName
	}
	if scl == "" {
		scl = defSCLPinName
	}
	if cs == "" {
		cs = defCSPinName
	}
	if rst == "" {
		rst = defRSTPinName
	}
	if fbdev == "" {
		fbdev = defFBDevName
	}
	if d.SDA = gpioreg.ByName(sda); d.SDA == nil {
		log.Fatal("SDA: gpio pin not found")
	}
	if d.SCL = gpioreg.ByName(scl); d.SDA == nil {
		log.Fatal("SCL: gpio pin not found")
	}
	if d.CS = gpioreg.ByName(cs); d.SDA == nil {
		log.Fatal("CS: gpio pin not found")
	}
	if d.RST = gpioreg.ByName(rst); d.RST == nil {
		log.Fatal("RST: gpio pin not found")
	}
	d.SDA.Out(gpio.Low)
	d.SCL.Out(gpio.Low)
	d.CS.Out(gpio.High)
	d.RST.Out(gpio.High)

	d.fb, err = framebuffer.Open(fbdev)
	if err != nil {
		log.Fatal("Couldn't open framebuffer")
	}

	return d
}

// Schliesst die Verbindung zum ILI9341.
func (d *GC9503CV) Close() {
	d.fb.Close()
}

// Führt die Initialisierung des Chips durch. initParams ist ein Slice
// von Hardware-spezifischen Einstellungen. Beim ILI9341 sind dies:
//
//	{ initMinimal, madctlParam }
func (d *GC9503CV) Init(rot byte) (w, h int) {
	bounds, _ := d.Init2(rot)
	size := bounds.Size()
	return int(size.X), int(size.Y)
}

func (d *GC9503CV) Init2(rot byte) (dispBounds, drawBounds geom.Rectangle) {
	var offset geom.Point
	var dispSize, drawSize geom.Point

	rotation := RotationType(rot)
	dispSize = geom.Point{shortSide, longSide}
	switch rotation {
	case Rot000, Rot180:
		offset = geom.Point{xOffset, yOffset}
		drawSize = geom.Point{shortSide, longSide}.Sub(offset.Mul(2))

	case Rot090, Rot270:
		offset = geom.Point{yOffset, xOffset}
		drawSize = geom.Point{longSide, shortSide}.Sub(offset.Mul(2))
	}

	d.Reset(true)
	for _, obj := range InitCmds {
		d.Cmd(obj.cmd)
		if len(obj.data) > 0 {
			d.DataArray(obj.data)
		}
		if obj.delay > 0 {
			time.Sleep(time.Duration(obj.delay) * time.Millisecond)
		}
	}

	dispBounds = geom.Rectangle{Max: dispSize}
	drawBounds = geom.NewRectangleWH(offset.X, offset.Y, drawSize.X, drawSize.Y)
	return
}

// Sende den Befehl in 'cmd' zum ILI9341.
func (d *GC9503CV) Cmd(cmd uint8) {
	d.CS.Out(gpio.Low)
	d.SDA.Out(gpio.Low)
	d.SCL.Out(gpio.Low)
	d.SCL.Out(gpio.High)
	d.send(cmd)
	d.CS.Out(gpio.High)
}

// Sende die Daten in 'value' (1 Byte) als Datenpaket zum ILI9341.
func (d *GC9503CV) Data8(value uint8) {
	d.CS.Out(gpio.Low)
	d.SDA.Out(gpio.High)
	d.SCL.Out(gpio.Low)
	d.SCL.Out(gpio.High)
	d.send(value)
	d.CS.Out(gpio.High)
}

// Sende die Daten in 'value' (4 By'tes) als Datenpaket zum ILI9341.
func (d *GC9503CV) Data32(value uint32) {}

// Sendet die Daten aus dem Slice 'buf' als Daten zum ILI9341. Dies ist bloss
// eine Hilfsfunktion, damit das Senden von Daten aus einem Slice einfacher
// aufzurufen ist und die ganzen Konvertierungen nicht im Hauptprogramm
// sichtbar sind.
func (d *GC9503CV) DataArray(buf []byte) {
	for _, b := range buf {
		d.Data8(b)
	}
}

func (d *GC9503CV) Reset(hw bool) {
	if hw {
		d.RST.Out(gpio.Low)
		time.Sleep(120 * time.Millisecond)
		d.RST.Out(gpio.High)
		time.Sleep(120 * time.Millisecond)
	} else {
		d.Cmd(0x01)
		time.Sleep(120 * time.Millisecond)
	}
}

func (d *GC9503CV) send(b byte) {
	for range 8 {
		d.SCL.Out(gpio.Low)
		if b&0x80 != 0x00 {
			d.SDA.Out(gpio.High)
		} else {
			d.SDA.Out(gpio.Low)
		}
		d.SCL.Out(gpio.High)
		b <<= 1
	}
}

func (d *GC9503CV) Send(img *iliimg.ILIImage) {
	//log.Printf("Bounds of the image: %v", img.Bounds())
	//if d.fb.Bounds() != img.Bounds() {
	//    log.Fatal("By now, image and screen must have equal size")
	//}
	i := img.PixOffset(img.Rect.Min.X, img.Rect.Min.Y)
	copy(d.fb.Pix[i:], img.Pix)
}

